export interface WordSpec {
  text: string;
  style: Phaser.Types.GameObjects.Text.TextStyle;
  /** Marks a word the story asked to emphasise. */
  emphasis?: boolean;
}

export interface LaidOutWord {
  text: Phaser.GameObjects.Text;
  x: number;
  y: number;
  emphasis: boolean;
}

/**
 * Measure-then-place word layout. Needed because each word is its own Text
 * object (so narration can emphasise individual words and reveal them one at
 * a time), which rules out Phaser's built-in word wrap.
 *
 * Coordinates come back centred on (0,0) so the caller can drop them straight
 * into a container.
 */
export function layoutWords(
  scene: Phaser.Scene,
  words: WordSpec[],
  opts: { maxWidth: number; lineSpacing: number },
): { words: LaidOutWord[]; width: number; height: number } {
  const made = words.map((w) => {
    const text = scene.add.text(0, 0, w.text, w.style).setOrigin(0.5, 0.5);
    return { text, emphasis: w.emphasis === true };
  });

  const spaceWidth = made.reduce((max, m) => Math.max(max, m.text.height), 0) * 0.24;
  const lines: { items: typeof made; width: number }[] = [];
  let current: typeof made = [];
  let currentWidth = 0;

  for (const item of made) {
    const advance = current.length === 0 ? item.text.width : spaceWidth + item.text.width;
    if (current.length > 0 && currentWidth + advance > opts.maxWidth) {
      lines.push({ items: current, width: currentWidth });
      current = [item];
      currentWidth = item.text.width;
    } else {
      current.push(item);
      currentWidth += advance;
    }
  }
  if (current.length > 0) lines.push({ items: current, width: currentWidth });

  const height = Math.max(1, lines.length) * opts.lineSpacing;
  const width = lines.reduce((max, l) => Math.max(max, l.width), 0);
  const out: LaidOutWord[] = [];

  lines.forEach((line, lineIndex) => {
    let cursor = -line.width / 2;
    const y = -height / 2 + opts.lineSpacing * (lineIndex + 0.5);
    for (const item of line.items) {
      const x = cursor + item.text.width / 2;
      out.push({ text: item.text, x, y, emphasis: item.emphasis });
      cursor += item.text.width + spaceWidth;
    }
  });

  return { words: out, width, height };
}

export interface BigButtonOptions {
  label: string;
  x: number;
  y: number;
  width?: number;
  height?: number;
  fill: number;
  ink: number;
  fontSize?: number;
  onPress: () => void;
  onHover?: (over: boolean) => void;
}

/**
 * The only navigation a 5-year-old should ever need: one enormous, springy,
 * unmissable button.
 */
export function createBigButton(
  scene: Phaser.Scene,
  opts: BigButtonOptions,
): Phaser.GameObjects.Container {
  const w = opts.width ?? 340;
  const h = opts.height ?? 116;
  const radius = h / 2;
  const container = scene.add.container(opts.x, opts.y);

  const glow = scene.add.image(0, 6, TEX.glow).setDisplaySize(w * 1.6, h * 2.1);
  glow.setTint(opts.fill).setAlpha(0.4);

  const shadow = scene.add.graphics();
  shadow.fillStyle(0x000000, 0.22);
  shadow.fillRoundedRect(-w / 2, -h / 2 + 10, w, h, radius);

  const face = scene.add.graphics();
  face.fillStyle(opts.fill, 1);
  face.fillRoundedRect(-w / 2, -h / 2, w, h, radius);
  face.fillStyle(0xffffff, 0.18);
  face.fillRoundedRect(-w / 2 + 8, -h / 2 + 7, w - 16, h * 0.42, radius * 0.7);

  const label = scene.add
    .text(0, 0, opts.label, {
      fontFamily: FONT.display,
      fontSize: `${opts.fontSize ?? 46}px`,
      color: cssColor(opts.ink),
      fontStyle: 'bold',
    })
    .setOrigin(0.5)
    .setLetterSpacing(2);

  container.add([glow, shadow, face, label]);
  container.setSize(w, h);
  container.setInteractive({ useHandCursor: true });

  scene.tweens.add({
    targets: container,
    scale: 1.035,
    duration: 1400,
    yoyo: true,
    repeat: -1,
    ease: 'Sine.easeInOut',
  });
  scene.tweens.add({
    targets: glow,
    alpha: 0.68,
    duration: 1100,
    yoyo: true,
    repeat: -1,
    ease: 'Sine.easeInOut',
  });

  let pressed = false;
  container.on('pointerover', () => {
    label.setScale(1.06);
    opts.onHover?.(true);
  });
  container.on('pointerout', () => {
    label.setScale(1);
    opts.onHover?.(false);
  });
  container.on('pointerdown', () => {
    label.setScale(0.94);
  });
  container.on('pointerup', () => {
    if (pressed) return;
    pressed = true;
    container.disableInteractive();
    scene.tweens.killTweensOf(container);
    scene.tweens.add({
      targets: container,
      scale: 0.9,
      duration: 90,
      yoyo: true,
      ease: 'Quad.easeOut',
      onComplete: () => opts.onPress(),
    });
  });

  return container;
}

function starPath(
  ctx: CanvasRenderingContext2D,
  cx: number,
  cy: number,
  points: number,
  outer: number,
  inner: number,
): void {
  const step = Math.PI / points;
  let angle = -Math.PI / 2;
  ctx.moveTo(cx + Math.cos(angle) * outer, cy + Math.sin(angle) * outer);
  for (let i = 0; i < points; i += 1) {
    angle += step;
    ctx.lineTo(cx + Math.cos(angle) * inner, cy + Math.sin(angle) * inner);
    angle += step;
    ctx.lineTo(cx + Math.cos(angle) * outer, cy + Math.sin(angle) * outer);
  }
  ctx.closePath();
}

function roundRect(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number,
): void {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}
