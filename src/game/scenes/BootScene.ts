/**
 * BootScene - the only place raw textures are made.
 *
 * There are zero image files in this project, so every sprite the engine uses
 * (glows, sparkles, stars, confetti, soft fades) is painted into a canvas
 * texture here at boot and tinted per-scene afterwards.
 */

export const SCENE_KEYS = {
  boot: 'Boot',
  home: 'Home',
  story: 'Story',
  completion: 'Completion',
} as const;

/** Texture keys generated by BootScene. Tint these, never recolour by hand. */
export const TEX = {
  glow: 'fx-glow',
  dot: 'fx-dot',
  spark: 'fx-spark',
  star: 'fx-star',
  ring: 'fx-ring',
  fade: 'fx-fade',
  confetti: 'fx-confetti',
  pixel: 'fx-pixel',
} as const;

/** Typography. Web-safe stacks only - no font files exist to load. */
export const FONT = {
  /** Storybook narration: warm, bookish, high legibility at large sizes. */
  story: 'Georgia, "Iowan Old Style", "Palatino Linotype", "Times New Roman", serif',
  /** Big friendly UI: titles, buttons, Mimo's voice. */
  display: '"Trebuchet MS", "Segoe UI", Verdana, Tahoma, sans-serif',
} as const;

export function cssColor(hex: number): string {
  return `#${(hex >>> 0).toString(16).padStart(6, '0').slice(-6)}`;
}

export class BootScene extends Phaser.Scene {
  constructor() {
    super(SCENE_KEYS.boot);
  }

  create(): void {
    this.buildTextures();
    this.scene.start(SCENE_KEYS.home);
  }

  private buildTextures(): void {
    this.paint(TEX.glow, 128, 128, (ctx, w, h) => {
      const g = ctx.createRadialGradient(w / 2, h / 2, 0, w / 2, h / 2, w / 2);
      g.addColorStop(0, 'rgba(255,255,255,1)');
      g.addColorStop(0.35, 'rgba(255,255,255,0.55)');
      g.addColorStop(0.72, 'rgba(255,255,255,0.16)');
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, w, h);
    });

    this.paint(TEX.dot, 32, 32, (ctx, w, h) => {
      const g = ctx.createRadialGradient(w / 2, h / 2, 0, w / 2, h / 2, w / 2);
      g.addColorStop(0, 'rgba(255,255,255,1)');
      g.addColorStop(0.62, 'rgba(255,255,255,0.92)');
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, w, h);
    });

    this.paint(TEX.spark, 64, 64, (ctx, w, h) => {
      const cx = w / 2;
      const cy = h / 2;
      const glow = ctx.createRadialGradient(cx, cy, 0, cx, cy, cx);
      glow.addColorStop(0, 'rgba(255,255,255,0.9)');
      glow.addColorStop(0.4, 'rgba(255,255,255,0.18)');
      glow.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = glow;
      ctx.fillRect(0, 0, w, h);

      // Four-point sparkle: concave arms pinched at the centre.
      ctx.fillStyle = 'rgba(255,255,255,1)';
      ctx.beginPath();
      ctx.moveTo(cx, 1);
      ctx.quadraticCurveTo(cx + 5, cy - 5, w - 1, cy);
      ctx.quadraticCurveTo(cx + 5, cy + 5, cx, h - 1);
      ctx.quadraticCurveTo(cx - 5, cy + 5, 1, cy);
      ctx.quadraticCurveTo(cx - 5, cy - 5, cx, 1);
      ctx.fill();
    });

    this.paint(TEX.star, 72, 72, (ctx, w, h) => {
      ctx.fillStyle = 'rgba(255,255,255,1)';
      ctx.beginPath();
      starPath(ctx, w / 2, h / 2 + 2, 5, w / 2 - 3, (w / 2 - 3) * 0.46);
      ctx.fill();
    });

    this.paint(TEX.ring, 128, 128, (ctx, w, h) => {
      const cx = w / 2;
      const cy = h / 2;
      const glow = ctx.createRadialGradient(cx, cy, w * 0.3, cx, cy, cx);
      glow.addColorStop(0, 'rgba(255,255,255,0)');
      glow.addColorStop(0.72, 'rgba(255,255,255,0.35)');
      glow.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = glow;
      ctx.fillRect(0, 0, w, h);

      ctx.strokeStyle = 'rgba(255,255,255,1)';
      ctx.lineWidth = 6;
      ctx.beginPath();
      ctx.arc(cx, cy, cx - 8, 0, Math.PI * 2);
      ctx.stroke();
    });

    this.paint(TEX.fade, 8, 256, (ctx, w, h) => {
      const g = ctx.createLinearGradient(0, 0, 0, h);
      g.addColorStop(0, 'rgba(255,255,255,1)');
      g.addColorStop(0.55, 'rgba(255,255,255,0.45)');
      g.addColorStop(1, 'rgba(255,255,255,0)');
      ctx.fillStyle = g;
      ctx.fillRect(0, 0, w, h);
    });

    this.paint(TEX.confetti, 16, 26, (ctx, w, h) => {
      ctx.fillStyle = 'rgba(255,255,255,1)';
      roundRect(ctx, 1, 1, w - 2, h - 2, 5);
      ctx.fill();
    });

    this.paint(TEX.pixel, 4, 4, (ctx, w, h) => {
      ctx.fillStyle = 'rgba(255,255,255,1)';
      ctx.fillRect(0, 0, w, h);
    });
  }

  private paint(
    key: string,
    width: number,
    height: number,
    draw: (ctx: CanvasRenderingContext2D, w: number, h: number) => void,
  ): void {
    if (this.textures.exists(key)) return;
    const texture = this.textures.createCanvas(key, width, height);
    if (!texture) return;
    const ctx = texture.getContext();
    ctx.clearRect(0, 0, width, height);
    draw(ctx, width, height);
    texture.refresh();
  }
}

